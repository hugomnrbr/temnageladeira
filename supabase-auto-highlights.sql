-- Tem na Geladeira: tabela exclusiva para os acessos usados nos rankings.
-- Não altera nem apaga a tabela recipe_views já existente.
create table if not exists public.recipe_view_events (
  id bigint generated by default as identity primary key,
  recipe_key text not null,
  viewed_at timestamptz not null default now()
);

create index if not exists recipe_view_events_viewed_at_idx
  on public.recipe_view_events (viewed_at desc);

create index if not exists recipe_view_events_recipe_key_idx
  on public.recipe_view_events (recipe_key);

alter table public.recipe_view_events enable row level security;

drop policy if exists "Anyone can register recipe view events" on public.recipe_view_events;
create policy "Anyone can register recipe view events"
  on public.recipe_view_events
  for insert to anon, authenticated
  with check (length(recipe_key) between 1 and 100);

drop policy if exists "Anyone can read recipe view events" on public.recipe_view_events;
create policy "Anyone can read recipe view events"
  on public.recipe_view_events
  for select to anon, authenticated
  using (true);

grant insert, select on public.recipe_view_events to anon, authenticated;
grant usage, select on sequence public.recipe_view_events_id_seq to anon, authenticated;
