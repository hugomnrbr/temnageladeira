-- Execute uma única vez no Supabase SQL Editor.
create table if not exists public.recipe_views (
  id bigint generated by default as identity primary key,
  recipe_key text not null,
  viewed_at timestamptz not null default now()
);
create index if not exists recipe_views_viewed_at_idx on public.recipe_views (viewed_at desc);
create index if not exists recipe_views_recipe_key_idx on public.recipe_views (recipe_key);
alter table public.recipe_views enable row level security;
drop policy if exists "Anyone can register recipe views" on public.recipe_views;
create policy "Anyone can register recipe views"
  on public.recipe_views for insert to anon, authenticated
  with check (length(recipe_key) between 1 and 100);
drop policy if exists "Anyone can read recipe views" on public.recipe_views;
create policy "Anyone can read recipe views"
  on public.recipe_views for select to anon, authenticated
  using (true);
grant insert, select on public.recipe_views to anon, authenticated;
grant usage, select on sequence public.recipe_views_id_seq to anon, authenticated;
