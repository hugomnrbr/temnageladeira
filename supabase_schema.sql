-- Esquema inicial Supabase para Tem na Geladeira (revise antes de executar)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.recipes (
  id bigint generated by default as identity primary key,
  name text not null, category text not null, time text not null default '',
  servings integer not null default 2, image_url text, needs text[] not null default '{}',
  ingredients text[] not null default '{}', steps text[] not null default '{}',
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.recipe_likes (
  recipe_id bigint not null references public.recipes(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(), primary key(recipe_id,user_id)
);
create table if not exists public.recipe_ratings (
  recipe_id bigint not null references public.recipes(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  primary key(recipe_id,user_id)
);
create table if not exists public.recipe_views (
  recipe_id bigint not null references public.recipes(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  viewed_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.recipes enable row level security;
alter table public.recipe_likes enable row level security;
alter table public.recipe_ratings enable row level security;
alter table public.recipe_views enable row level security;
-- Leitura pública do catálogo; escrita apenas por administradores via políticas/claims seguras.
create policy "recipes are readable" on public.recipes for select using (true);
create policy "users read profiles" on public.profiles for select to authenticated using (id = auth.uid());
create policy "users manage own likes" on public.recipe_likes for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "users manage own ratings" on public.recipe_ratings for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "views insert" on public.recipe_views for insert with check (user_id is null or user_id = auth.uid());
