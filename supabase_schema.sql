-- Recursos da comunidade: perfis de criadores, solicitações e receitas submetidas.
create table if not exists public.creator_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  bio text not null default '',
  instagram text,
  tiktok text,
  youtube text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.community_recipes (
  id bigint generated by default as identity primary key,
  creator_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  category text not null,
  time text not null default '',
  servings integer not null default 2,
  image_url text,
  ingredients text[] not null default '{}',
  steps text[] not null default '{}',
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  featured boolean not null default false,
  views integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.recipe_ingredients (
  id bigint generated by default as identity primary key,
  name text not null unique,
  emoji text not null default '🥗',
  category text not null default 'Outros',
  created_at timestamptz not null default now()
);
alter table public.creator_profiles enable row level security;
alter table public.community_recipes enable row level security;
alter table public.recipe_ingredients enable row level security;
create policy "approved creator profiles are public" on public.creator_profiles for select using (status = 'approved' or user_id = auth.uid());
create policy "users request own creator profile" on public.creator_profiles for insert to authenticated with check (user_id = auth.uid() and status = 'pending');
create policy "users update own pending profile" on public.creator_profiles for update to authenticated using (user_id = auth.uid() and status <> 'approved') with check (user_id = auth.uid() and status in ('pending','rejected'));
create policy "approved community recipes are public" on public.community_recipes for select using (status = 'approved');
create policy "approved creators submit recipes for review" on public.community_recipes for insert to authenticated with check (creator_id = auth.uid() and status = 'pending' and exists(select 1 from public.creator_profiles cp where cp.user_id = auth.uid() and cp.status = 'approved'));
create policy "creators edit own pending recipes" on public.community_recipes for update to authenticated using (creator_id = auth.uid() and status = 'pending') with check (creator_id = auth.uid() and status = 'pending');
create policy "ingredients are public" on public.recipe_ingredients for select using (true);
-- Ações de aprovação/administração devem ser executadas por uma conta administrativa confiável
-- com políticas específicas baseadas em claims/RLS; nunca permita que o usuário comum altere status ou featured.
